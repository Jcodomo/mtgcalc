// Builds assets/income-reader.js - the Income Calculator's income document reader (OCR clean-up, classify, extractFields) -
// from income-calculator.html, so the Loan Suite's Documents pages read income documents with exactly the same code.
// The Loan Suite reader (assets/js/06-...) hands classify and extractFields to window.MTIncomeReader when it is loaded.
// Run: node tools/build-income-reader.mjs            write assets/income-reader.js
//      node tools/build-income-reader.mjs --check    fail when assets/income-reader.js is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(path.join(root, 'income-calculator.html'), 'utf8');
const a = html.indexOf('/* ---------- number / line helpers ---------- */'), b = html.indexOf('/* ---------- reading the file ---------- */');
const c = html.indexOf('const AUS_LABEL'), d = html.indexOf('</script>', c);
if (a < 0 || b < 0 || c < 0 || d < 0) throw new Error('the reader was not found in income-calculator.html');
const ver = (html.match(/assets\/income-rules\.js\?v=([\d.]+)/) || [])[1] || '';
const out = `/* Mortgage Suite - income document reader. GENERATED by tools/build-income-reader.mjs from income-calculator.html; edit the
   reader there and run the tool again. Loaded on the Loan Suite pages, whose Documents reader uses it (window.MTIncomeReader). */
(function () {
${html.slice(a, b)}
${html.slice(c, d)}
window.MTIncomeReader = {classify: classify, extractFields: extractFields, lines: lines, ocrFix: ocrFix, from: 'income-calculator.html${ver ? ' ' + ver : ''}'};
})();
`;
const file = path.join(root, 'assets/income-reader.js');
if (process.argv.includes('--check')) {
  if (!existsSync(file) || readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== out.replace(/\r\n/g, '\n')) { console.error('assets/income-reader.js is out of date: run node tools/build-income-reader.mjs'); process.exit(1); }
  console.log('assets/income-reader.js is up to date');
} else { writeFileSync(file, out); console.log(`wrote assets/income-reader.js (${out.length.toLocaleString()} bytes)`); }
